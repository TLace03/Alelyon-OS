def _unexpected_rng(*args, **kwargs):
    raise AssertionError("resource refusal must happen before resampling")


def test_resample_count_refuses_before_rng_work(monkeypatch):
    monkeypatch.setattr(execcert.np.random, "default_rng", _unexpected_rng)
    series = pd.Series(
        np.arange(4, dtype=float),
        index=pd.date_range("2024-01-02", periods=4),
        name="SYN",
    )
    cert = execcert.certified_run(
        PROGRAM,
        fetcher=_Fetcher(series, 1e-4),
        K=execcert.MAX_REPLAY_RESAMPLES + 1,
        seed=1,
    )
    assert cert.refused is True
    assert cert.reason == "K=10001 exceeds the verifier limit of 10000 resamples"


def test_aggregate_replay_work_refuses_before_rng_work(monkeypatch):
    monkeypatch.setattr(execcert.np.random, "default_rng", _unexpected_rng)
    series = pd.Series(
        np.arange(120, dtype=float),
        index=pd.date_range("2024-01-02", periods=120),
        name="SYN",
    )
    term = 'mean(price("SYN"))'
    cert = execcert.certified_run(
        "show " + " + ".join([term] * 15),
        fetcher=_Fetcher(series, 1e-4),
        K=execcert.MAX_REPLAY_RESAMPLES,
        seed=1,
    )
    assert cert.refused is True
    assert cert.reason == (
        "replay work 72007200 exceeds the verifier limit of 50000000 units "
        "(rows=120, K=10000, AST nodes=60)"
    )


