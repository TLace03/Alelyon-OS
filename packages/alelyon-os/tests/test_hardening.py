def test_cli_file_depth_and_structural_resource_limits(tmp_path, monkeypatch):
    assert cli._MAX_JSON_FILE_BYTES == 64 * 1024 * 1024
    assert cli._MAX_JSON_DEPTH == 64

    path = tmp_path / "bounded.json"
    path.write_bytes(b"[0, 0, 0]")
    monkeypatch.setattr(cli, "_MAX_JSON_FILE_BYTES", 4)
    with pytest.raises(ValueError, match="exceeds"):
        cli._load_json(str(path))

    monkeypatch.setattr(cli, "_MAX_JSON_FILE_BYTES", 1024)
    path.write_text("[" * 65 + "0" + "]" * 65, encoding="utf-8")
    with pytest.raises(ValueError, match="nesting"):
        cli._load_json(str(path))

    path.write_text("[0, 0, 0]", encoding="utf-8")
    monkeypatch.setattr(cli, "_MAX_JSON_NODES", 3)
    with pytest.raises(ValueError, match="node limit"):
        cli._load_json(str(path))

    monkeypatch.setattr(cli, "_MAX_JSON_NODES", 2_000_000)
    monkeypatch.setattr(cli, "_MAX_JSON_CONTAINER_ITEMS", 2)
    with pytest.raises(ValueError, match="item limit"):
        cli._load_json(str(path))

    monkeypatch.setattr(cli, "_MAX_JSON_CONTAINER_ITEMS", 1_000_000)
    monkeypatch.setattr(cli, "_MAX_JSON_STRING_BYTES", 3)
    path.write_text('"four"', encoding="utf-8")
    with pytest.raises(ValueError, match="string limit"):
        cli._load_json(str(path))


