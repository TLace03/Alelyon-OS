PROGRAM = 'show mean(price("SYN"))'


class _Fetcher:
    def __init__(self, series, delta):
        self.series = series
        self.delta = delta

    def get(self, kind, key):
        assert (kind, key) == ("price", "SYN")
        return execcert.FetchedSeries(
            series=self.series.copy(),
            deltas=np.full(len(self.series), self.delta, dtype=float),
            uncertified=0,
        )


